/**
 * Loads `docs/assets/tabela-precos-prazos-2026.json` if present on disk,
 * merging with BUILTIN_CATALOG_2026 so that both local monorepo and
 * serverless deployments have 100% of the 2026 catalog from the PDF.
 */
export function loadOfficialCatalog2026(): CatalogExam2026Item[] {
  const candidatePaths = [
    path.resolve(process.cwd(), '../docs/assets/tabela-precos-prazos-2026.json'),
    path.resolve(process.cwd(), 'docs/assets/tabela-precos-prazos-2026.json'),
    path.resolve(__dirname, '../../../../docs/assets/tabela-precos-prazos-2026.json'),
  ];

  for (const jsonPath of candidatePaths) {
    try {
      if (fs.existsSync(jsonPath)) {
        const raw = fs.readFileSync(jsonPath, 'utf8');
        const parsed = JSON.parse(raw);
        const list = Array.isArray(parsed) ? parsed : parsed.exams || [];
        if (Array.isArray(list) && list.length > 0) {
          return list.map((item: any) => {
            const code = String(item.code || '').trim().padStart(3, '0');
            const builtin = BUILTIN_CATALOG_2026.find((b) => b.code === code);
            const fixedId =
              code === '057'
                ? 'exam-hemograma'
                : code === '000'
                ? 'exam-bioquimico'
                : code === '108'
                ? 'exam-copro'
                : code === '145'
                ? 'exam-urocultura'
                : item.id || builtin?.id || `exam-${code}`;

            return {
              id: fixedId,
              code,
              name: String(item.name || builtin?.name || '').trim(),
              section: String(item.section || builtin?.section || 'Patologia Clínica').trim(),
              delivery_days: Number(item.delivery_days ?? builtin?.delivery_days ?? 1),
              delivery_time_label: String(
                item.delivery_time_label ||
                  builtin?.delivery_time_label ||
                  `${item.delivery_days ?? 1} dia(s) útil(eis)`
              ).trim(),
              price: Number(item.price ?? builtin?.price ?? 50),
              material: String(
                item.material || item.tube_type || builtin?.material || 'Tubo padrão laboratorial'
              ).trim(),
              preparation: String(
                item.preparation || builtin?.preparation || 'Jejum de 6 a 8 horas.'
              ).trim(),
              label_qty: Number(item.label_qty ?? builtin?.label_qty ?? 1),
            };
          });
        }
      }
    } catch {
      // Fallback to built-in catalog if JSON is still being written
    }
  }

  return BUILTIN_CATALOG_2026.map((item) => ({
    ...item,
    id: item.id || `exam-${item.code}`,
  }));
}
